test('patient recap is centralized under Capaian Unit; Mutu Klinis has no duplicate results tab', () => {
  const home = read('components/HomeClient.tsx')
  const overview = read('components/OverviewDashboard.tsx')
  assert.match(overview, /<QualityResultsWorkspace mode="indicators"/)
  assert.match(overview, /title="Capaian Unit"/)
  assert.match(overview, /canViewAllRooms=\{canViewAllRooms\}/)
  assert.doesNotMatch(home, /aria-label="Tampilan audit mutu"/)
  assert.doesNotMatch(home, />Hasil Capaian<\/button>/)
  assert.doesNotMatch(home, /active==='quality'&&qualityResultsView\?<QualityResultsWorkspace/)
  assert.match(home, /tab==='hasil-capaian'\)\{setActive\('home'\)/)
})

test('Register Pasien owns patient creation and workbook import; Mutu Klinis only enters indicator values', () => {
  const register = read('components/RegisterPasienWorkspace.tsx')
  const quality = read('components/QualityIndicatorWorkspace.tsx')
  assert.match(register, />Tambah Pasien<\/button>/)
  assert.match(register, />Rekapan Pasien<\/button>/)
  assert.match(register, /workspaceMode="register"/)
  assert.match(register, /registerTab=\{tab\}/)
  assert.match(quality, /workspaceMode='indicators'/)
  assert.match(quality, /showRegisterInput&&<section className="glass aqRegisterEntryCard"/)
  assert.match(quality, /isRegisterMode&&registerTab==='add'[^]*className="aqBtn aqImportButton"/)
  assert.match(quality, /className="aqBtn primary aqAddButton"/)
  assert.match(quality, /!isRegisterMode&&<section className="aqIndicatorSection"/)
  assert.match(quality, /Simpan Hasil Mutu/)
  assert.match(quality, /Simpan Data Pasien/)
})

test('unit achievement scope is shared and whole-hospital selection clears the saved room', () => {
  const home = read('components/HomeClient.tsx')
  const overview = read('components/OverviewDashboard.tsx')
  const results = read('components/QualityResultsWorkspace.tsx')
  const quality = read('components/QualityIndicatorWorkspace.tsx')
  assert.match(home, /selectedQualityRoomId,setSelectedQualityRoomId/)
  assert.match(home, /effectiveQualityRoomId/)
  assert.match(home, /roomId=\{effectiveQualityRoomId\} roomName=/)
  assert.match(home, /initialRoomId=\{effectiveQualityRoomId\}/)
  assert.match(home, /onRoomChange=\{updateSelectedQualityRoom\}/g)
  assert.match(home, /window\.sessionStorage\.setItem\(storageKey,String\(nextRoomId\)\)/)
  assert.match(home, /window\.sessionStorage\.removeItem\(storageKey\)/)
  assert.match(overview, /onRoomChange=\{onRoomChange\}/)
  assert.match(results, /<option value="all">Seluruh rumah sakit<\/option>/)
  assert.match(results, /onRoomChange\?\.\(null\)/)
  assert.match(results, /if\(selectedRoom!=null\) query=query\.eq\('room_id',selectedRoom\)/)
  assert.match(quality, /onRoomChange\?\.\(roomId\)/)
})
