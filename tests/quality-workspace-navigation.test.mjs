import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('Halaman Utama and Register Pasien are ordered and all roles open the Welcome Page after login', () => {
  const home = read('components/HomeClient.tsx')
  const registry = read('lib/aureka/module-registry.ts')
  const nav = read('components/OverviewDashboard.tsx')
  assert.match(registry, /label: 'Halaman Utama'/)
  assert.match(registry, /id: 'patients',[\s\S]*label: 'Register Pasien'/)
  assert.ok(registry.indexOf("id: 'patients'") < registry.indexOf("id: 'quality'"), 'Register Pasien must precede Mutu Klinis')
  assert.match(home, /'register-pasien':'patients'/)
  assert.match(home, /active==='patients'\? <RegisterPasienWorkspace/)
  assert.match(home, /setActive\('home'\);setQualityOpen\(false\);setQualityResultsView\(null\)/)
  assert.doesNotMatch(home, /if\(currentRole==='VALIDATOR'\)\{setActive\('quality'\)/)
  assert.match(nav, />Welcome Page<\/button>/)
  assert.match(nav, />Infografis<\/button>/)
  assert.match(nav, />Capaian Unit<\/button>/)
})

