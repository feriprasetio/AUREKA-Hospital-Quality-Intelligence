import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('Arktik is the active workspace skin and Solid override layers are not loaded', () => {
  const layout = read('app/layout.tsx')
  const home = read('components/HomeClient.tsx')
  assert.match(layout, /<html lang="id" data-skin="arktik"/)
  assert.ok(home.includes('data-aureka-theme='))
  for (const legacy of ["./solid-default.css", "./aureka-solid-enterprise.css", "./aureka-solid-navigation.css"]) {
    assert.ok(!layout.includes("import '" + legacy + "'"), legacy + ' must not override Arktik')
  }
  assert.ok(layout.includes("import './aureka-global.css'"))
  const bundle = read('app/aureka-global.css')
  assert.ok(bundle.indexOf("@import './theme-arktik-dark.css'") < bundle.indexOf("@import './aureka-navigation-pill.css'"))
  assert.ok(bundle.indexOf("@import './dark-mode-mobile-fixes.css'") < bundle.indexOf("@import './aureka-navigation-pill.css'"))
  assert.ok(bundle.indexOf("@import './aureka-global-navigation.css'") < bundle.indexOf("@import './aureka-navigation-pill.css'"))
  assert.ok(bundle.indexOf("@import './aureka-navigation-repair.css'") < bundle.indexOf("@import './aureka-acrylic-navigation-polish.css'"))
  assert.ok(bundle.includes("@import './aureka-acrylic-navigation-polish.css';") && bundle.indexOf("@import './aureka-acrylic-navigation-polish.css';") < bundle.indexOf("@import './aureka-layout-integrity.css';"))
  for (const legacy of ["clinical-ui.css", "medidash-ui.css", "medidash-polish.css", "solid-default.css", "aureka-solid-navigation.css", "aureka-solid-enterprise.css"]) {
    assert.ok(!bundle.includes(legacy), legacy + ' must be removed from the active UI bundle')
  }
  const acrylic = read('app/aureka-acrylic-navigation-polish.css')
  assert.ok(acrylic.includes('--aureka-acrylic-sidebar:'))
  assert.ok(acrylic.includes('.sidebarDomainTrigger.navActive'))
  assert.ok(acrylic.includes('background: transparent !important'))
  assert.ok(acrylic.includes('stroke: currentColor !important'))
  assert.ok(acrylic.includes('grid-template-columns: 84px minmax(0, 1fr) !important'))
  const typography = read('app/typography.css')
  const tokens = read('app/design-tokens.css')
  const base = read('app/globals.css')
  assert.match(typography, /Plus Jakarta Sans/)
  assert.ok(tokens.includes('--aureka-font-sans: var(--font-aureka), "Plus Jakarta Sans"'))
  assert.match(tokens, /--aureka-color-primary: #16507a/)
  assert.ok(base.includes('font-family:var(--font-aureka),"Plus Jakarta Sans"'))
})

test('Arktik uses bundled Plus Jakarta Sans and does not download Inter', () => {
  const skin = read('app/theme-arktik.css')
  assert.doesNotMatch(skin, /fonts\.googleapis\.com|font-family:\s*["']Inter["']/i)
  assert.match(skin, /var\(--font-aureka\)/)
})

test('sidebar exposes the eight requirement categories from one registry; modules expand contextually', () => {
  const home = read('components/HomeClient.tsx')
  const registry = read('lib/aureka/module-registry.ts')
  const navCss = read('app/aureka-navigation-consolidated.css')
  const repairCss = read('app/aureka-navigation-repair.css')
  assert.ok(home.includes('aria-label="Delapan kategori utama AUREKA"'))
  assert.ok(home.includes('visibleSidebarDomains.map'))
  for (const id of ['command_center','patient_registry','clinical_performance','quality_patient_safety','hospital_management','education_training','director_supervisory_board','settings']) assert.ok(registry.includes("id:'" + id + "'"), id)
  assert.ok(home.includes('aria-expanded={isExpanded}'))
  assert.ok(home.includes('hidden={!isExpanded}'))
  assert.ok(home.includes('role="heading" aria-level={2}'))
  assert.ok(home.includes("import UnifiedModuleNavigation from '@/components/navigation/UnifiedModuleNavigation'"))
  assert.ok(home.includes('<UnifiedModuleNavigation'))
  assert.ok(home.includes('activeNestedNavGroup'))
  assert.match(home, /\\{activeNavGroups.length>0&&<UnifiedModuleNavigation/)
  assert.doesNotMatch(home, /sidebarModuleChildren|sidebarModuleChild/)
  for (const legacy of ['sidebarTreeChildren', 'sidebarNestedGroup', 'closedNav', 'toggleNav(']) assert.ok(!home.includes(legacy))
  assert.ok(navCss.includes('.workspaceNavigationRail'))
  assert.ok(navCss.includes('.workspaceRoot .sidebar .sidebarTreeChildren'))
  assert.ok(repairCss.includes('.sidebarDomainTrigger'))
  assert.ok(repairCss.includes('.sidebarDomainItems'))
  assert.ok(repairCss.includes('.sidebarDomainItem.active'))
})

test('global navigation uses balanced one-line smart overflow and keeps the active tab visible', () => {
  const component = read('components/navigation/UnifiedModuleNavigation.tsx')
  const css = read('app/aureka-global-navigation.css')
  assert.ok(component.includes('new ResizeObserver(calculate)'))
  assert.ok(component.includes("const primaryMin = items.length ?"))
  assert.ok(component.includes("const secondaryMin = subItems.length ?"))
  assert.ok(component.includes('overflowItems.map'))
  assert.ok(component.includes('overflowSubItems.map'))
  assert.ok(component.includes('<summary aria-label='))
  assert.ok(component.includes("onClick={() => selectPrimary(item.id)}"))
  assert.ok(component.includes("onClick={() => selectSecondary(item.id)}"))
  assert.match(css, /--aureka-nav-primary:\s*#172a40/)
  assert.match(css, /--aureka-nav-secondary:\s*#dcebf8/)
  assert.match(css, /workspaceNavigationOverflowMenu/)
  assert.match(css, /@media \(max-width: 720px\)/)
  assert.doesNotMatch(css, /position:\s*sticky/)
})

