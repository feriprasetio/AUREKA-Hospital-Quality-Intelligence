test('Secretariat parser reads PDF, DOCX, XLSX, CSV, TXT and image metadata without generative AI', async () => {
  const parser = await read('supabase/functions/aureka-secretariat-parse/index.ts')
  for (const marker of ['pdfjs.getDocument','JSZip.loadAsync','xl/workbook.xml','parseCsv','imageInfo','extracted_text','parsed_metadata']) has(parser,marker)
  assert.doesNotMatch(parser,/GEMINI_API_KEY|generativelanguage\\.googleapis\\.com|api\\.openai\\.com|openrouter/i)
  has(parser,'PDF tidak memiliki lapisan teks digital yang terbaca')
  has(parser,'does not call any generative-AI API')
})

test('Secretariat Storage access is restricted to unit scope or the exact global Meeting ID path', async () => {
  const sql = await read('supabase/migrations/20261121083500_secretariat_global_storage_scope.sql')
  has(sql,"(storage.foldername(name))[1]='global'")
  has(sql,"(storage.foldername(name))[3] = any(array['undangan','materi','absensi','notulensi','gambar']::text[])")
  has(sql,'aureka_system.can_manage_pmkp_workspace()')
  has(sql,'m.room_id is null')
  const workspace = await read('components/governance/SecretariatWorkspace.tsx')
  has(workspace,"activeMeeting.room_id == null ? 'global' : String(activeMeeting.room_id)")
})

