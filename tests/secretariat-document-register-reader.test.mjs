import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const read = (path) => readFile(new URL('../' + path, import.meta.url), 'utf8')
const has = (source, value, message = value) => assert.ok(source.includes(value), message)

test('Secretariat renders the requested register columns and a popup for the five UMANG file categories', async () => {
  const workspace = await read('components/governance/SecretariatWorkspace.tsx')
  for (const column of ['<th>No</th>','<th>Tanggal Dokumen</th>','<th>Nomor Dokumen</th>','<th>Judul Dokumen</th>','<th>Jenis Dokumen</th>','<th>Isi Dokumen</th>']) has(workspace,column)
  for (const category of ["id: 'undangan'","id: 'materi'","id: 'absensi'","id: 'notulensi'","id: 'gambar'"]) has(workspace,category)
  has(workspace,'role="dialog"')
  has(workspace,'Buka Isi Dokumen')
  has(workspace,'Unggah banyak berkas sekaligus')
  has(workspace,'multiple')
  has(workspace,'Unggah dan Baca')
})

