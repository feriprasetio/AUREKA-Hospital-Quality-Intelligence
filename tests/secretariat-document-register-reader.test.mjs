test('Secretariat parser reads PDF, DOCX, XLSX, CSV, TXT and image metadata without generative AI', async () => {
  const parser = await read('supabase/functions/aureka-secretariat-parse/index.ts')
  for (const marker of ['pdfjs.getDocument','JSZip.loadAsync','xl/workbook.xml','parseCsv','imageInfo','extracted_text','parsed_metadata']) has(parser,marker)
  assert.doesNotMatch(parser,/GEMINI_API_KEY|generativelanguage|api\\.openai\\.com|openrouter/i)
  has(parser,'PDF tidak memiliki lapisan teks digital yang terbaca')
  has(parser,'does not call any generative-AI API')
})

test('legacy Storage policies remain documented, but new Secretariat records never reference binary sources', async () => {
  const legacy = await read('supabase/migrations/20261121083500_secretariat_global_storage_scope.sql')
  const schema = await read('supabase/migrations/20261122180000_zero_file_archive_schema.sql')
  const lock = await read('supabase/migrations/20261122181000_zero_file_storage_policies.sql')
  const workspace = await read('components/governance/SecretariatWorkspace.tsx')
  has(legacy, 'aureka_system.can_manage_pmkp_workspace()')
  has(schema, 'pmkp_meeting_documents_data_only_path_check')
  has(lock, 'AS RESTRICTIVE FOR INSERT TO anon, authenticated')
  has(workspace, "source_mode:'data_only'")
  assert.doesNotMatch(workspace, /\.storage\.from\(/)
})

test('browser-only Secretariat ingestion stores validated extracted text, never original binary files', async () => {
  const workspace = await read('components/governance/SecretariatWorkspace.tsx')
  has(workspace, 'readLocalDocument(item.file)')
  has(workspace, 'extracted_text:extracted')
  has(workspace, 'parsed_metadata:')
  has(workspace, 'extraction_status:extractionStatus')
  has(workspace, 'makeStructuredDocx(')
  has(workspace, 'printStructuredContent(')
  assert.doesNotMatch(workspace, /\.upload\(|createSignedUrl\(|\.download\(/)
  const migration = await read('supabase/migrations/20261121083000_secretariat_document_register_reader.sql')
  has(migration, 'extracted_text text not null default')
  has(migration, 'parsed_metadata jsonb not null default')
})
