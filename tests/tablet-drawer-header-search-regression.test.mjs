import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('legacy Aurora cannot expand or detach the original tablet sidebar', () => {
  const aurora = read('app/aurora.css')
  const start = aurora.indexOf('/* Workspace shell geometry belongs exclusively')
  const end = aurora.indexOf('/* Monitoring di samping Tanya AUREKA', start)
  assert.ok(start >= 0 && end > start)
  const shell = aurora.slice(start, end)
  assert.doesNotMatch(shell,/aside\.sidebar\s*\{[^}]*?width\s*:/)
  assert.doesNotMatch(shell,/\.workspaceHeaderBar\s*\{[^}]*?(?:margin|top|border-radius)\s*:/)
  assert.doesNotMatch(aurora,/\.workspaceRoot:not\(\.sidebarIsCollapsed\) aside\.sidebar\s*\{[^}]*max-width:\s*none\s*!important/)
  assert.doesNotMatch(aurora,/\.workspaceRoot\.workspaceDesk:not\(\.sidebarIsCollapsed\)\s*\{\s*grid-template-columns:\s*256px/)
})

test('desktop and tablet sidebar are pinned, visible and scrollable without a scrim', () => {
  const css = read('app/aureka-navigation-system.css')
  const start = css.indexOf('/* Device navigation contract:')
  const end = css.indexOf('@media (max-width: 720px) {',start)
  assert.ok(start >= 0 && end > start)
  const pinned = css.slice(start,end)
  assert.match(pinned,/@media \(min-width: 721px\)/)
  assert.match(pinned,/position: sticky !important/)
  assert.match(pinned,/transform: none !important/)
  assert.match(pinned,/visibility: visible !important/)
  assert.match(pinned,/pointer-events: auto !important/)
  assert.match(pinned,/height: calc\(100dvh - 24px\) !important/)
  assert.match(pinned,/\.workspaceDrawerClose,[\s\S]*?\.workspaceSidebarMenuButton,[\s\S]*?\.workspaceScrim\s*\{\s*display: none !important/)
  assert.match(pinned,/body > \.workspaceNativeNavigation\s*\{\s*display: none !important/)
  assert.match(css,/\.sidebarDomainNav\s*\{[\s\S]*?overflow-y: auto !important/)
  assert.doesNotMatch(pinned,/width:\s*min\(360px/)
})

