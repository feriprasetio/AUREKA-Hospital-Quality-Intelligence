begin;

-- Extend the existing PMKP activity register; preserve every existing Meeting ID and row.
alter table aureka_system.pmkp_meetings
  add column if not exists register_no bigint generated by default as identity,
  add column if not exists document_date date not null default current_date,
  add column if not exists document_number text;

create unique index if not exists pmkp_meetings_register_no_uidx
  on aureka_system.pmkp_meetings(register_no);
create index if not exists pmkp_meetings_document_date_idx
  on aureka_system.pmkp_meetings(document_date desc, register_no desc);
create index if not exists pmkp_meetings_document_number_idx
  on aureka_system.pmkp_meetings(lower(document_number))
  where document_number is not null and btrim(document_number) <> '';
create index if not exists pmkp_meetings_meeting_type_idx
  on aureka_system.pmkp_meetings(meeting_type, meeting_date desc);

-- Each uploaded file remains in private Storage; only extracted text and structured metadata
-- are stored in Postgres for search, preview, reporting and automated register population.
alter table aureka_system.pmkp_meeting_documents
  add column if not exists original_filename text,
  add column if not exists extracted_text text not null default '',
  add column if not exists parsed_metadata jsonb not null default '{}'::jsonb,
  add column if not exists extraction_engine text,
  add column if not exists extraction_status text not null default 'pending'
    check (extraction_status in ('pending','completed','metadata_only','manual_review','failed')),
  add column if not exists document_date date,
  add column if not exists document_number text,
  add column if not exists document_title text,
  add column if not exists extraction_error text;

create index if not exists pmkp_meeting_documents_type_idx
  on aureka_system.pmkp_meeting_documents(meeting_id,document_type,uploaded_at desc);
create index if not exists pmkp_meeting_documents_number_idx
  on aureka_system.pmkp_meeting_documents(lower(document_number))
  where document_number is not null and btrim(document_number) <> '';

grant select,insert,update on aureka_system.pmkp_meetings to authenticated;
grant select,insert,update on aureka_system.pmkp_meeting_documents to authenticated;

drop policy if exists pmkp_meeting_children_update on aureka_system.pmkp_meeting_documents;
create policy pmkp_meeting_children_update
on aureka_system.pmkp_meeting_documents for update to authenticated
using (
  exists (
    select 1 from aureka_system.pmkp_meetings m
    where m.id=meeting_id
      and aureka_system.can_manage_pmkp_workspace()
      and aureka_system.can_access_room_or_global(m.room_id)
  )
)
with check (
  uploaded_by=(select auth.uid())
  and exists (
    select 1 from aureka_system.pmkp_meetings m
    where m.id=meeting_id
      and aureka_system.can_manage_pmkp_workspace()
      and aureka_system.can_access_room_or_global(m.room_id)
  )
);

commit;